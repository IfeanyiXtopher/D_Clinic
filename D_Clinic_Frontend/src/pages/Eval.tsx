import { type ReactNode, useEffect, useState } from "react";
import { api, type EvalCard, type EvalReport, type Registry } from "../api";
import { SimpleEval } from "../simple/EvalView";

const HIDE = [
  /1\s*GB|2\s*GB|VPS|RAM/i,
  /Ollama|LLM_PROVIDER|DistilBERT|Qwen 0\.6|GPU|pgvector/i,
  /templated briefing|template quality|template is the safety|swaps in the template/i,
  /live row is skipped|mlflow|this host may not/i,
  /do not fit|optional\. If `|n\/a unless/i,
];

function leaky(text: string): boolean {
  return HIDE.some((re) => re.test(text));
}

function sanitize(md: string): string {
  return md
    .replace(/\r\n/g, "\n")
    .split("\n")
    .filter((line) => {
      if (leaky(line)) return false;
      if (/^Auto-generated by/.test(line)) return false;
      if (/^\| template \|/.test(line)) return false;
      if (/^\| llm \(optional\)/.test(line)) return false;
      return true;
    })
    .join("\n")
    .replace(/## PDSQI-9-style rubric \(template\)/g, "## Briefing quality")
    .replace(/## Generators\n\n[\s\S]*?(?=\n## )/, "")
    .replace(/\n{3,}/g, "\n\n");
}

function inline(text: string): ReactNode {
  const parts: ReactNode[] = [];
  const re = /(\*\*[^*]+\*\*|`[^`]+`)/g;
  let last = 0;
  let i = 0;
  let m: RegExpExecArray | null;
  const src = text.replace(/\\\*/g, "*");
  while ((m = re.exec(src))) {
    if (m.index > last) parts.push(src.slice(last, m.index));
    const tok = m[0];
    if (tok.startsWith("**")) parts.push(<strong key={i++}>{tok.slice(2, -2)}</strong>);
    else parts.push(<span key={i++}>{tok.slice(1, -1)}</span>);
    last = m.index + tok.length;
  }
  if (last < src.length) parts.push(src.slice(last));
  return parts.length ? parts : text;
}

function cells(line: string): string[] {
  let s = line.trim();
  if (s.startsWith("|")) s = s.slice(1);
  if (s.endsWith("|")) s = s.slice(0, -1);
  return s.split("|").map((c) => c.replace(/\*\*/g, "").trim());
}

function isSep(line: string): boolean {
  return /^\|?[\s:-|]+$/.test(line.trim()) && line.includes("-");
}

function ReportView({ body }: { body: string }) {
  const lines = sanitize(body).split("\n");
  const blocks: ReactNode[] = [];
  let i = 0;
  let k = 0;
  while (i < lines.length) {
    const start = i;
    const line = lines[i];
    if (!line.trim()) { i += 1; continue; }
    if (line.startsWith("# ")) {
      blocks.push(<h3 key={k++} className="report-h">{inline(line.slice(2))}</h3>);
      i += 1; continue;
    }
    if (line.startsWith("## ")) {
      blocks.push(<h3 key={k++} className="report-h">{inline(line.slice(3))}</h3>);
      i += 1; continue;
    }
    if (line.startsWith("### ")) {
      blocks.push(<h4 key={k++} className="report-h4">{inline(line.slice(4))}</h4>);
      i += 1; continue;
    }
    if (line.trim().startsWith("|")) {
      const raw: string[] = [];
      while (i < lines.length && lines[i].trim().startsWith("|")) {
        if (!isSep(lines[i])) raw.push(lines[i]);
        i += 1;
      }
      const rows = raw.map(cells).filter((row) => row.some(Boolean) && !leaky(row.join(" ")) && row[0]?.toLowerCase() !== "template");
      if (rows.length >= 2) {
        const [headers, ...bodyRows] = rows;
        blocks.push(
          <div key={k++} className="report-table-wrap">
            <table className="plain">
              <thead>
                <tr>{headers.map((h, hi) => <th key={hi}>{inline(h)}</th>)}</tr>
              </thead>
              <tbody>
                {bodyRows.map((row, ri) => (
                  <tr key={ri}>{row.map((c, ci) => <td key={ci}>{inline(c)}</td>)}</tr>
                ))}
              </tbody>
            </table>
          </div>,
        );
      }
      continue;
    }
    if (/^[-*] /.test(line.trim())) {
      const items: string[] = [];
      while (i < lines.length && /^[-*] /.test(lines[i].trim())) {
        const item = lines[i].trim().replace(/^[-*] /, "");
        if (!leaky(item)) items.push(item);
        i += 1;
      }
      if (items.length) {
        blocks.push(
          <ul key={k++} className="report-list">
            {items.map((item, ii) => <li key={ii}>{inline(item)}</li>)}
          </ul>,
        );
      }
      continue;
    }
    const para: string[] = [];
    while (i < lines.length && lines[i].trim() && !lines[i].startsWith("#") && !lines[i].trim().startsWith("|") && !/^[-*] /.test(lines[i].trim())) {
      para.push(lines[i]);
      i += 1;
    }
    const text = para.join(" ");
    if (text && !leaky(text)) blocks.push(<p key={k++}>{inline(text)}</p>);
    if (i === start) i += 1;
  }
  return <div className="report">{blocks}</div>;
}

export function EvalPage() {
  const [cards, setCards] = useState<EvalCard[]>([]);
  const [reg, setReg] = useState<Registry | null>(null);
  const [open, setOpen] = useState<EvalReport | null>(null);
  const [loading, setLoading] = useState<string | null>(null);
  const [err, setErr] = useState("");

  useEffect(() => {
    Promise.all([api.reports(), api.registry()])
      .then(([c, r]) => { setCards(c); setReg(r); })
      .catch((e: Error) => setErr(e.message));
  }, []);

  async function toggle(id: string) {
    if (open?.id === id) {
      setOpen(null);
      return;
    }
    setErr("");
    setLoading(id);
    try {
      setOpen(await api.report(id));
    } catch (e) {
      setErr((e as Error).message);
    } finally {
      setLoading(null);
    }
  }

  return (
    <SimpleEval
      cards={cards}
      reg={reg}
      open={open}
      loading={loading}
      err={err}
      toggle={toggle}
      report={(body) => <ReportView body={body} />}
    />
  );
}
